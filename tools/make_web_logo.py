"""Regenerates src/web_logo.h, the logo the PLC web server serves at /logo.png.

    pip install pillow
    python tools/make_web_logo.py <app_icon_foreground.png> src/web_logo.h

Use IntelliGuardPhase-Admin-Panel/assets/icon/app_icon_foreground.png as the
source. The mark is cropped out of the artwork, centred on a white rounded tile
(the app's adaptive icon is the same mark on white, and the tile keeps it legible
on the dark top bar and in a dark browser tab) and stored as a ~2 KB 32-colour
palette PNG with transparent corners.

After changing the logo, bump LOGO_VER in src/web_handler.cpp so browsers drop
their cached copy.
"""
import io
import sys

from PIL import Image, ImageDraw

SRC, OUT = sys.argv[1], sys.argv[2]
OUT_PX, FILL, RADIUS, SUPERSAMPLE = 192, 0.72, 0.22, 4

mark = Image.open(SRC).convert("RGBA")
mark = mark.crop(mark.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox())

big = OUT_PX * SUPERSAMPLE
tile = Image.new("RGBA", (big, big), (0, 0, 0, 0))
ImageDraw.Draw(tile).rounded_rectangle((0, 0, big - 1, big - 1), radius=int(big * RADIUS), fill=(255, 255, 255, 255))
k = big * FILL / max(mark.size)
scaled = mark.resize((round(mark.width * k), round(mark.height * k)), Image.LANCZOS)
tile.alpha_composite(scaled, ((big - scaled.width) // 2, (big - scaled.height) // 2))
tile = tile.resize((OUT_PX, OUT_PX), Image.LANCZOS)

q = tile.quantize(colors=32, method=Image.FASTOCTREE, dither=Image.NONE)
pal = q.getpalette(rawmode="RGBA")
for i in range(len(pal) // 4):  # quantising nudges the tile's white; keep it pure
    r, g, b, a = pal[i * 4:i * 4 + 4]
    if a >= 250 and min(r, g, b) >= 244:
        pal[i * 4:i * 4 + 4] = [255, 255, 255, 255]
q.putpalette(pal, rawmode="RGBA")
buf = io.BytesIO()
q.save(buf, "PNG", optimize=True)
png = buf.getvalue()

lines = [
    "// Generated by tools/make_web_logo.py - do not edit by hand.",
    "// The logo served at GET /logo.png (top bar, sign-in page, browser tab icon).",
    "#pragma once",
    "",
    "#include <Arduino.h>",
    "",
    "static const uint8_t WEB_LOGO_PNG[] PROGMEM = {",
]
for i in range(0, len(png), 16):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in png[i:i + 16]) + ",")
lines += ["};", "", "static const size_t WEB_LOGO_PNG_LEN = sizeof(WEB_LOGO_PNG);", ""]
with open(OUT, "wb") as f:  # the working tree is CRLF (core.autocrlf=true)
    f.write("\r\n".join(lines).encode("ascii"))
print(f"{OUT}: {len(png)} byte PNG, {OUT_PX}x{OUT_PX}")
